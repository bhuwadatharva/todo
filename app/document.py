"""
Document Generator Module.
Generates polished, executive-ready Microsoft Word (.docx) documents using python-docx.
Includes professional typography, color palettes, metadata callout tables, and headers/footers.
"""
import os
import datetime
from pathlib import Path
from typing import List, Optional

import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import parse_xml, OxmlElement
from docx.oxml.ns import nsdecls, qn

from app.config import OUTPUT_DIR
from app.models import Plan, SectionContent


# Color Palette (Executive Navy & Slate Theme)
COLOR_PRIMARY = RGBColor(0x1E, 0x3A, 0x8A)      # Deep Navy #1E3A8A
COLOR_SECONDARY = RGBColor(0x25, 0x63, 0xEB)    # Royal Blue #2563EB
COLOR_TEXT_DARK = RGBColor(0x1F, 0x29, 0x37)    # Charcoal #1F2937
COLOR_MUTED = RGBColor(0x4B, 0x55, 0x63)        # Slate Grey #4B5563
COLOR_BORDER = "CBD5E1"                         # Light Slate Border #CBD5E1
HEX_HEADER_BG = "1E3A8A"                        # Navy Table Header Fill
HEX_CALLOUT_BG = "F1F5F9"                       # Light Callout Background #F1F5F9
HEX_ALT_ROW_BG = "F8FAFC"                       # Alternating row fill


def _set_cell_background(cell, hex_color: str):
    """Set background color of a table cell using XML shading."""
    tc_pr = cell._tc.get_or_add_tcPr()
    # Remove existing shading if present
    for child in list(tc_pr):
        if child.tag.endswith('shd'):
            tc_pr.remove(child)
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hex_color}"/>')
    tc_pr.append(shd)


def _set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Set inner cell padding in twips (1 pt = 20 twips)."""
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_mar = parse_xml(
        f'<w:tcMar {nsdecls("w")}>'
        f'<w:top w:w="{top}" w:type="dxa"/>'
        f'<w:bottom w:w="{bottom}" w:type="dxa"/>'
        f'<w:left w:w="{left}" w:type="dxa"/>'
        f'<w:right w:w="{right}" w:type="dxa"/>'
        f'</w:tcMar>'
    )
    tc_pr.append(tc_mar)


def create_docx_report(plan: Plan, sections: List[SectionContent], request_text: str) -> Path:
    """
    Builds a beautifully styled Word document based on the executed plan and sections.
    Saves the file to OUTPUT_DIR and returns its absolute Path.
    """
    doc = Document()

    # Configure 1-inch standard margins
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)
        
        # Configure Header & Footer
        header = section.header
        hp = header.paragraphs[0]
        hp.text = f"{plan.title} | Executive Strategy Brief"
        hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        if hp.runs:
            hp.runs[0].font.size = Pt(8.5)
            hp.runs[0].font.color.rgb = COLOR_MUTED

        footer = section.footer
        fp = footer.paragraphs[0]
        fp.text = "Confidential – Generated by Autonomous AI Agent"
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if fp.runs:
            fp.runs[0].font.size = Pt(8.5)
            fp.runs[0].font.color.rgb = COLOR_MUTED

    # 1. Document Title
    title_p = doc.add_paragraph()
    title_p.paragraph_format.space_before = Pt(0)
    title_p.paragraph_format.space_after = Pt(4)
    run_title = title_p.add_run(plan.title)
    run_title.font.name = "Calibri"
    run_title.font.size = Pt(24)
    run_title.font.bold = True
    run_title.font.color.rgb = COLOR_PRIMARY

    # Subtitle
    sub_p = doc.add_paragraph()
    sub_p.paragraph_format.space_before = Pt(0)
    sub_p.paragraph_format.space_after = Pt(16)
    run_sub = sub_p.add_run(plan.subtitle)
    run_sub.font.name = "Calibri"
    run_sub.font.size = Pt(13)
    run_sub.font.italic = True
    run_sub.font.color.rgb = COLOR_MUTED

    # 2. Metadata Summary Box (Table)
    meta_table = doc.add_table(rows=3, cols=2)
    meta_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    meta_table.autofit = False

    meta_items = [
        ("Generation Date", datetime.datetime.now().strftime("%B %d, %Y – %H:%M:%S UTC")),
        ("Total Tasks Executed", f"{len(plan.tasks)} Autonomous Tasks"),
        ("Original Request", (request_text[:140] + "...") if len(request_text) > 140 else request_text)
    ]

    for i, (label, val) in enumerate(meta_items):
        cell_lbl = meta_table.cell(i, 0)
        cell_lbl.width = Inches(2.0)
        _set_cell_background(cell_lbl, HEX_CALLOUT_BG)
        _set_cell_margins(cell_lbl, 80, 80, 120, 120)
        p = cell_lbl.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(label)
        r.font.bold = True
        r.font.size = Pt(9.5)
        r.font.color.rgb = COLOR_PRIMARY

        cell_val = meta_table.cell(i, 1)
        cell_val.width = Inches(4.5)
        _set_cell_background(cell_val, "FFFFFF")
        _set_cell_margins(cell_val, 80, 80, 120, 120)
        p2 = cell_val.paragraphs[0]
        p2.paragraph_format.space_after = Pt(0)
        r2 = p2.add_run(val)
        r2.font.size = Pt(9.5)
        r2.font.color.rgb = COLOR_TEXT_DARK

    doc.add_paragraph().paragraph_format.space_after = Pt(12)

    # 3. Assumptions & Resolution Box
    if plan.assumptions:
        h_assump = doc.add_paragraph()
        h_assump.paragraph_format.space_before = Pt(12)
        h_assump.paragraph_format.space_after = Pt(4)
        r_ah = h_assump.add_run("Project Assumptions & Scope Clarifications")
        r_ah.font.name = "Calibri"
        r_ah.font.size = Pt(14)
        r_ah.font.bold = True
        r_ah.font.color.rgb = COLOR_SECONDARY

        desc_p = doc.add_paragraph()
        desc_p.paragraph_format.space_after = Pt(6)
        r_desc = desc_p.add_run(
            "The autonomous agent identified the following implicit constraints and explicit assumptions to resolve ambiguities:"
        )
        r_desc.font.size = Pt(10)
        r_desc.font.italic = True
        r_desc.font.color.rgb = COLOR_MUTED

        for assumption in plan.assumptions:
            ap = doc.add_paragraph(style='List Bullet')
            ap.paragraph_format.space_after = Pt(3)
            ar = ap.add_run(assumption)
            ar.font.size = Pt(10)
            ar.font.color.rgb = COLOR_TEXT_DARK

        doc.add_paragraph().paragraph_format.space_after = Pt(8)

    # 4. Sections Generated from Tasks
    for sec in sections:
        # Section Heading
        h = doc.add_paragraph()
        h.paragraph_format.space_before = Pt(16)
        h.paragraph_format.space_after = Pt(6)
        h.paragraph_format.keep_with_next = True
        hrun = h.add_run(sec.section_title)
        hrun.font.name = "Calibri"
        hrun.font.size = Pt(15)
        hrun.font.bold = True
        hrun.font.color.rgb = COLOR_PRIMARY

        # Paragraphs
        for paragraph_text in sec.paragraphs:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            run = p.add_run(paragraph_text)
            run.font.name = "Calibri"
            run.font.size = Pt(10.5)
            run.font.color.rgb = COLOR_TEXT_DARK

        # Bullet Points
        if sec.bullet_points:
            for bp in sec.bullet_points:
                bp_para = doc.add_paragraph(style='List Bullet')
                bp_para.paragraph_format.space_after = Pt(3)
                bp_run = bp_para.add_run(bp)
                bp_run.font.name = "Calibri"
                bp_run.font.size = Pt(10)
                bp_run.font.color.rgb = COLOR_TEXT_DARK

        # Structured Table (if available)
        if sec.table_headers and sec.table_rows:
            num_cols = len(sec.table_headers)
            num_rows = len(sec.table_rows) + 1
            tbl = doc.add_table(rows=num_rows, cols=num_cols)
            tbl.alignment = WD_TABLE_ALIGNMENT.CENTER

            # Header Row
            for c_idx, head_text in enumerate(sec.table_headers):
                c = tbl.cell(0, c_idx)
                _set_cell_background(c, HEX_HEADER_BG)
                _set_cell_margins(c, 100, 100, 120, 120)
                p = c.paragraphs[0]
                p.paragraph_format.space_after = Pt(0)
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                r = p.add_run(head_text)
                r.font.bold = True
                r.font.size = Pt(9.5)
                r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)

            # Data Rows
            for r_idx, row_data in enumerate(sec.table_rows):
                row_bg = HEX_ALT_ROW_BG if r_idx % 2 == 1 else "FFFFFF"
                for c_idx in range(num_cols):
                    val = row_data[c_idx] if c_idx < len(row_data) else ""
                    c = tbl.cell(r_idx + 1, c_idx)
                    _set_cell_background(c, row_bg)
                    _set_cell_margins(c, 80, 80, 120, 120)
                    p = c.paragraphs[0]
                    p.paragraph_format.space_after = Pt(0)
                    r = p.add_run(str(val))
                    r.font.size = Pt(9.5)
                    r.font.color.rgb = COLOR_TEXT_DARK

            doc.add_paragraph().paragraph_format.space_after = Pt(8)

    # 5. Generate Safe Unique Filename
    clean_title = "".join(c for c in plan.title if c.isalnum() or c in (" ", "_", "-")).rstrip()
    slug = "_".join(clean_title.split()[:4]).lower()
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"{slug}_{timestamp}.docx" if slug else f"strategy_doc_{timestamp}.docx"

    file_path = OUTPUT_DIR / filename
    doc.save(str(file_path))
    return file_path
